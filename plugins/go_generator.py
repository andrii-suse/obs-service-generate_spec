#!/usr/bin/env python3
"""
Go RPM Spec Generator Plugin for obs-service-generate_spec
Inspects go.mod, vendors dependencies into vendor.tar.<compression>, and emits an RPM .spec file.
"""

import argparse
import datetime
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

GENERATOR_SIGNATURE = "AUTO-GENERATED by obs-service-generate_spec"


def parse_go_mod(go_mod_path: Path):
    """Parses go.mod to extract module path, Go version, and requirement flag."""
    module_path = ""
    go_version = "1.21"
    has_requirements = False

    if not go_mod_path.exists():
        return module_path, go_version, has_requirements

    content = go_mod_path.read_text(encoding="utf-8", errors="replace")

    # Match module directive: module github.com/foo/bar
    m_mod = re.search(r"^\s*module\s+([^\s]+)", content, re.MULTILINE)
    if m_mod:
        module_path = m_mod.group(1).strip()

    # Match go version: go 1.27.0 or go 1.23
    m_go = re.search(r"^\s*go\s+([0-9]+(?:\.[0-9]+)*(?:\.[0-9]+)?)", content, re.MULTILINE)
    if m_go:
        go_version = m_go.group(1).strip()

    # Match require block or inline require
    if re.search(r"^\s*require\s*[\(\w]", content, re.MULTILINE):
        has_requirements = True

    return module_path, go_version, has_requirements


def detect_package_name(module_path: str, override_name: str | None, source_dir: Path) -> str:
    """Derives a clean package name from override, module path, or directory name."""
    if override_name:
        return override_name

    if module_path:
        # Strip trailing version suffixes like /v11, /v2
        clean_path = re.sub(r"/v\d+$", "", module_path)
        parts = clean_path.split("/")
        if parts:
            name = parts[-1].strip()
            if name:
                return name

    return source_dir.resolve().name or "application"


def detect_url(module_path: str) -> str:
    """Builds a project URL from the module path."""
    if not module_path:
        return ""
    clean_path = re.sub(r"/v\d+$", "", module_path)
    if any(clean_path.startswith(prefix) for prefix in ("github.com/", "gitlab.com/", "gitea.com/", "codeberg.org/")):
        return f"https://{clean_path}"
    if "/" in clean_path:
        return f"https://{clean_path}"
    return ""


def detect_license(source_dir: Path) -> tuple[str, str]:
    """Detects license file name and SPDX license identifier."""
    license_files = ["LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "COPYING.md"]
    found_file = ""
    for name in license_files:
        candidate = source_dir / name
        if candidate.is_file():
            found_file = name
            break

    if not found_file:
        return "MIT", ""

    try:
        content = (source_dir / found_file).read_text(encoding="utf-8", errors="replace")[:2000]
    except Exception:
        content = ""

    spdx = "MIT"
    if "Apache License" in content:
        spdx = "Apache-2.0"
    elif "Mozilla Public License" in content or "MPL-2.0" in content:
        spdx = "MPL-2.0"
    elif "General Public License" in content:
        if "version 3" in content or "GPLv3" in content:
            spdx = "GPL-3.0-only"
        else:
            spdx = "GPL-2.0-only"
    elif "BSD 3-Clause" in content:
        spdx = "BSD-3-Clause"
    elif "BSD 2-Clause" in content:
        spdx = "BSD-2-Clause"
    elif "MIT License" in content or "Permission is hereby granted" in content:
        spdx = "MIT"

    return spdx, found_file


def detect_readme(source_dir: Path) -> tuple[str, str, str]:
    """Detects README file, extracting Summary and Description."""
    readme_files = ["README.md", "README.rst", "README.txt", "README"]
    found_file = ""
    for name in readme_files:
        candidate = source_dir / name
        if candidate.is_file():
            found_file = name
            break

    summary = ""
    description_lines = []

    if found_file:
        try:
            raw_text = (source_dir / found_file).read_text(encoding="utf-8", errors="replace")

            # Check if there is an image alt text at the top: alt="fzf - a command-line fuzzy finder"
            alt_match = re.search(r'alt=["\'](?:[a-zA-Z0-9_\-]+\s*[-–:]\s*)?([^"\']{10,80})["\']', raw_text[:2000])
            if alt_match:
                candidate_summary = alt_match.group(1).strip()
                if not any(k in candidate_summary.lower() for k in ["badge", "status", "build", "license", "version", "stars", "merch"]):
                    summary = candidate_summary

            lines = raw_text.splitlines()
            for line in lines:
                s = line.strip()
                # Skip HTML tags, markdown headings, badges, codeblocks, horizontal rules, and promotional links
                if (
                    not s
                    or s.startswith("#")
                    or s.startswith("[!")
                    or s.startswith("<")
                    or s.startswith("```")
                    or re.match(r"^[-=_*]{3,}$", s)
                    or "t-shirt" in s.lower()
                    or "stickers now available" in s.lower()
                    or "buy me a coffee" in s.lower()
                ):
                    continue

                # Strip HTML tags embedded in line
                cleaned = re.sub(r"<[^>]+>", "", s)
                # Clean markdown formatting like **bold** or [links](...)
                cleaned = re.sub(r"\[([^\]]+)\]\([^\)]+\)", r"\1", cleaned)
                cleaned = re.sub(r"[*_`]", "", cleaned).strip()

                # Ensure line has meaningful alphabetic text
                if len(re.findall(r"[a-zA-Z]", cleaned)) < 10:
                    continue

                if not summary:
                    summary = cleaned[:80].rstrip(".")
                description_lines.append(cleaned)
                if len(description_lines) >= 8:
                    break
        except Exception:
            pass

    if not summary:
        summary = "Command-line tool written in Go"
    if not description_lines:
        description = summary
    else:
        description = "\n".join(description_lines)

    return summary, description, found_file


def detect_main_entrypoint(source_dir: Path) -> str:
    """Finds where package main lives: root, cmd/<subpkg>, or examples/<subpkg>."""
    # 1. Check root directory
    for go_file in source_dir.glob("*.go"):
        try:
            content = go_file.read_text(encoding="utf-8", errors="replace")[:500]
            if re.search(r"^\s*package\s+main\b", content, re.MULTILINE):
                return "."
        except Exception:
            pass

    # 2. Check cmd/* subdirectories
    cmd_dir = source_dir / "cmd"
    if cmd_dir.is_dir():
        for sub in sorted(cmd_dir.iterdir()):
            if sub.is_dir():
                for go_file in sub.glob("*.go"):
                    try:
                        content = go_file.read_text(encoding="utf-8", errors="replace")[:500]
                        if re.search(r"^\s*package\s+main\b", content, re.MULTILINE):
                            return f"./cmd/{sub.name}"
                    except Exception:
                        pass

    # 3. Check examples/* subdirectories
    examples_dir = source_dir / "examples"
    if examples_dir.is_dir():
        for sub in sorted(examples_dir.iterdir()):
            if sub.is_dir():
                for go_file in sub.glob("*.go"):
                    try:
                        content = go_file.read_text(encoding="utf-8", errors="replace")[:500]
                        if re.search(r"^\s*package\s+main\b", content, re.MULTILINE):
                            return f"./examples/{sub.name}"
                    except Exception:
                        pass

    return "."


def detect_systemd_service(source_dir: Path, pkg_name: str) -> str | None:
    """Finds a systemd service file matching the package name."""
    candidates = [
        f"{pkg_name}.service",
        f"systemd/{pkg_name}.service",
        f"packaging/{pkg_name}.service",
        f"packaging/systemd/{pkg_name}.service",
        f"contrib/{pkg_name}.service",
    ]
    for c in candidates:
        if (source_dir / c).is_file():
            return c

    # Fallback: check if there's exactly one .service file in root or systemd/
    root_services = list(source_dir.glob("*.service"))
    if len(root_services) == 1:
        return root_services[0].name

    systemd_services = list(source_dir.glob("systemd/*.service"))
    if len(systemd_services) == 1:
        return f"systemd/{systemd_services[0].name}"

    return None


def detect_man_page(source_dir: Path, pkg_name: str) -> str | None:
    """Finds a man1 page matching the package name."""
    candidates = [
        f"{pkg_name}.1",
        f"packaging/{pkg_name}.1",
        f"packaging/man/{pkg_name}.1",
        f"docs/{pkg_name}.1",
        f"man/{pkg_name}.1",
        f"man/man1/{pkg_name}.1",
    ]
    for c in candidates:
        if (source_dir / c).is_file():
            return c
    return None


def compute_manifest_checksum(source_dir: Path) -> str:
    """Computes SHA256 of go.mod and go.sum for cache validation."""
    hasher = hashlib.sha256()
    for name in ["go.mod", "go.sum"]:
        file_path = source_dir / name
        if file_path.is_file():
            hasher.update(file_path.read_bytes())
    return hasher.hexdigest()


def update_or_create_changes(source_dir: Path, outdir: Path, pkg_name: str, version: str):
    """Creates or updates <name>.changes with the current release entry."""
    changes_file = outdir / f"{pkg_name}.changes"
    now_str = datetime.datetime.now(datetime.timezone.utc).strftime("%a %b %d %H:%M:%S UTC %Y")
    maintainer = "obs-service-generate_spec <opensuse-packaging@opensuse.org>"

    new_entry = f"""-------------------------------------------------------------------
{now_str} - {maintainer}

- Update to version {version}
"""

    existing_file = None
    for p in [outdir, source_dir]:
        candidate = p / f"{pkg_name}.changes"
        if candidate.is_file():
            existing_file = candidate
            break

    if existing_file:
        existing_content = existing_file.read_text(encoding="utf-8", errors="replace")
        if f"version {version}" not in existing_content and f"to {version}" not in existing_content:
            changes_file.write_text(new_entry + "\n" + existing_content, encoding="utf-8")
            print(f"Appended version {version} entry to {changes_file}")
        elif existing_file != changes_file:
            shutil.copy2(existing_file, changes_file)
    else:
        initial_entry = f"""-------------------------------------------------------------------
{now_str} - {maintainer}

- Initial automated package generation for version {version}
"""
        changes_file.write_text(initial_entry, encoding="utf-8")
        print(f"Created initial changes file: {changes_file}")


def create_vendor_archive(source_dir: Path, outdir: Path, compression: str, vendor_mode: str) -> bool:
    """Vendors dependencies and creates vendor.tar.<compression>, using SHA256 caching."""
    if vendor_mode == "disable":
        return False

    vendor_archive_name = f"vendor.tar.{compression}"
    out_archive = outdir / vendor_archive_name
    checksum_file = outdir / f"{vendor_archive_name}.sha256"
    current_checksum = compute_manifest_checksum(source_dir)

    # 1. Check if an existing vendor archive matches the manifest checksum
    for comp in ["zst", "xz", "gz"]:
        candidate = source_dir / f"vendor.tar.{comp}"
        cand_sha = source_dir / f"vendor.tar.{comp}.sha256"
        if candidate.is_file():
            if cand_sha.is_file():
                try:
                    if cand_sha.read_text().strip() == current_checksum:
                        print(f"Notice: Reusing vendor archive '{candidate.name}' (manifest checksum matched).")
                        if candidate != out_archive:
                            shutil.copy2(candidate, out_archive)
                            shutil.copy2(cand_sha, checksum_file)
                        return True
                    else:
                        print(f"Notice: Manifest changed since last vendor run. Regenerating '{vendor_archive_name}'.")
                except Exception:
                    pass
            else:
                # If no checksum file exists alongside existing vendor archive, reuse it
                if candidate != out_archive:
                    shutil.copy2(candidate, out_archive)
                checksum_file.write_text(current_checksum)
                return True

    # 2. Check if vendor directory exists or run `go mod vendor`
    vendor_dir = source_dir / "vendor"
    if not vendor_dir.is_dir():
        print(f"Running 'go mod vendor' in {source_dir}...")
        try:
            res = subprocess.run(["go", "mod", "vendor"], cwd=source_dir, capture_output=True, text=True, timeout=120)
            if res.returncode != 0:
                print(f"Warning: 'go mod vendor' exited with {res.returncode}: {res.stderr.strip()}", file=sys.stderr)
        except Exception as e:
            print(f"Warning: could not execute 'go mod vendor': {e}", file=sys.stderr)

    if not vendor_dir.is_dir() or not any(vendor_dir.iterdir()):
        print("Notice: No vendor directory or dependencies found. Skipping vendor archive.")
        return False

    print(f"Packaging {vendor_dir} into {out_archive}...")
    if compression == "zst":
        # tar -c vendor | zstd -T0 -19 -o <out_archive>
        tar_proc = subprocess.Popen(["tar", "-cf", "-", "vendor"], cwd=source_dir, stdout=subprocess.PIPE)
        with open(out_archive, "wb") as f_out:
            zstd_proc = subprocess.Popen(["zstd", "-T0", "-19", "-o", str(out_archive)], stdin=tar_proc.stdout)
            tar_proc.stdout.close()
            zstd_proc.communicate()
    elif compression == "xz":
        subprocess.run(["tar", "-cJf", str(out_archive), "vendor"], cwd=source_dir, check=True)
    elif compression == "gz":
        subprocess.run(["tar", "-czf", str(out_archive), "vendor"], cwd=source_dir, check=True)

    if out_archive.is_file():
        checksum_file.write_text(current_checksum)
        return True

    return False


def main():
    parser = argparse.ArgumentParser(description="Go Spec Generator Plugin")
    parser.add_argument("--manifest-path", required=True, help="Path to go.mod")
    parser.add_argument("--source-dir", required=True, help="Path to root source directory")
    parser.add_argument("--outdir", required=True, help="Output directory for generated files")
    parser.add_argument("--name", default=None, help="Override package name")
    parser.add_argument("--version", default="@VERSION@", help="Override version")
    parser.add_argument("--compression", default="zst", choices=["zst", "xz", "gz"], help="Compression format")
    parser.add_argument("--vendor", default="auto", choices=["auto", "enable", "disable"], help="Vendor mode")
    args = parser.parse_args()

    source_dir = Path(args.source_dir).resolve()
    outdir = Path(args.outdir).resolve()
    go_mod_path = Path(args.manifest_path).resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    module_path, go_version, has_requirements = parse_go_mod(go_mod_path)
    pkg_name = detect_package_name(module_path, args.name, source_dir)
    pkg_url = detect_url(module_path)
    pkg_license, license_file = detect_license(source_dir)
    pkg_summary, pkg_description, readme_file = detect_readme(source_dir)
    entrypoint = detect_main_entrypoint(source_dir)
    service_file = detect_systemd_service(source_dir, pkg_name)
    man_page = detect_man_page(source_dir, pkg_name)

    # Handle vendoring
    has_vendor = False
    has_existing_vendor_tar = any((source_dir / f"vendor.tar.{comp}").is_file() for comp in ["zst", "xz", "gz"])
    if has_requirements or args.vendor == "enable" or (source_dir / "vendor").is_dir() or has_existing_vendor_tar:
        has_vendor = create_vendor_archive(source_dir, outdir, args.compression, args.vendor)

    # Prepare Spec File fields
    year = datetime.date.today().year
    source1_line = f"Source1:        vendor.tar.{args.compression}" if has_vendor else ""
    prep_args = "-a1" if has_vendor else ""

    comp_br = ""
    if has_vendor:
        if args.compression == "zst":
            comp_br = "BuildRequires:  zstd"
        elif args.compression == "xz":
            comp_br = "BuildRequires:  xz"

    systemd_br = ""
    systemd_install = ""
    systemd_scriptlets = ""
    systemd_files = ""
    if service_file:
        systemd_br = "BuildRequires:  systemd-rpm-macros\n%{?systemd_ordering}"
        systemd_install = f"install -D -m 0644 {service_file} %{{buildroot}}%{{_unitdir}}/%{{name}}.service"
        systemd_scriptlets = """%pre
%service_add_pre %{name}.service

%post
%service_add_post %{name}.service

%preun
%service_del_preun %{name}.service

%postun
%service_del_postun %{name}.service"""
        systemd_files = "%{_unitdir}/%{name}.service"

    man_install = ""
    man_files = ""
    if man_page:
        man_install = f"install -D -m 0644 {man_page} %{{buildroot}}%{{_mandir}}/man1/%{{name}}.1"
        man_files = "%{_mandir}/man1/%{name}.1*"

    license_line = f"%license {license_file}" if license_file else ""
    doc_line = f"%doc {readme_file}" if readme_file else ""

    build_cmd = "go build -mod=vendor -buildmode=pie"
    if entrypoint and entrypoint != ".":
        build_cmd += f" -o %{{name}} {entrypoint}"

    spec_content = f"""#
# spec file for package {pkg_name}
#
# {GENERATOR_SIGNATURE}. DO NOT EDIT DIRECTLY.
#
# Copyright (c) {year} SUSE LLC and contributors
#
# All modifications and additions to the file contributed by third parties
# remain the property of their copyright owners, unless otherwise agreed
# upon. The license for this file, and modifications and additions to the
# file, is the same license as for the pristine package itself.
#

Name:           {pkg_name}
Version:        {args.version}
Release:        0
Summary:        {pkg_summary}
License:        {pkg_license}
URL:            {pkg_url}
Source0:        %{{name}}-%{{version}}.tar.gz
{source1_line}
BuildRequires:  golang-packaging
BuildRequires:  golang(API) >= {go_version}
{comp_br}
{systemd_br}
%{{go_nostrip}}
%{{go_provides}}

%description
{pkg_description}

%prep
%autosetup -p1 {prep_args}

%build
{build_cmd}

%install
install -D -m 0755 %{{name}} %{{buildroot}}%{{_bindir}}/%{{name}}
{systemd_install}
{man_install}

{systemd_scriptlets}

%files
{license_line}
{doc_line}
%{{_bindir}}/%{{name}}
{systemd_files}
{man_files}

%changelog
"""
    # Clean up excess blank lines
    spec_content = re.sub(r"\n{3,}", "\n\n", spec_content)

    out_spec = outdir / f"{pkg_name}.spec"
    out_spec.write_text(spec_content, encoding="utf-8")
    print(f"Generated spec file: {out_spec}")

    # Generate or update <name>.changes
    update_or_create_changes(source_dir, outdir, pkg_name, args.version)


if __name__ == "__main__":
    main()
